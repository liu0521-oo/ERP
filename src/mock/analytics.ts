export const getAnalyticsStats = (data: Analytics[] = analytics) => {
  const totalOrders = data.reduce((sum, a) => sum + a.orders, 0)
  const totalRevenue = data.reduce((sum, a) => sum + a.revenue, 0)
  const totalVisitors = data.reduce((sum, a) => sum + a.visitors, 0)
  const avgConversionRate = (data.reduce((sum, a) => sum + a.conversionRate, 0) / data.length).toFixed(2)

  const prevTotalOrders = data.slice(0, Math.floor(data.length / 2)).reduce((sum, a) => sum + a.orders, 0)
  const currentTotalOrders = data.slice(Math.floor(data.length / 2)).reduce((sum, a) => sum + a.orders, 0)
  const ordersGrowth = ((currentTotalOrders - prevTotalOrders) / prevTotalOrders * 100).toFixed(1)

  const prevTotalRevenue = data.slice(0, Math.floor(data.length / 2)).reduce((sum, a) => sum + a.revenue, 0)
  const currentTotalRevenue = data.slice(Math.floor(data.length / 2)).reduce((sum, a) => sum + a.revenue, 0)
  const revenueGrowth = ((currentTotalRevenue - prevTotalRevenue) / prevTotalRevenue * 100).toFixed(1)

  const prevTotalVisitors = data.slice(0, Math.floor(data.length / 2)).reduce((sum, a) => sum + a.visitors, 0)
  const currentTotalVisitors = data.slice(Math.floor(data.length / 2)).reduce((sum, a) => sum + a.visitors, 0)
  const visitorsGrowth = ((currentTotalVisitors - prevTotalVisitors) / prevTotalVisitors * 100).toFixed(1)

  const prevAvgConversion = data.slice(0, Math.floor(data.length / 2)).reduce((sum, a) => sum + a.conversionRate, 0) / Math.floor(data.length / 2)
  const currAvgConversion = data.slice(Math.floor(data.length / 2)).reduce((sum, a) => sum + a.conversionRate, 0) / (data.length - Math.floor(data.length / 2))
  const conversionGrowth = ((currAvgConversion - prevAvgConversion) / prevAvgConversion * 100).toFixed(1)

  return {
    totalOrders,
    totalRevenue,
    totalVisitors,
    avgConversionRate: parseFloat(avgConversionRate),
    ordersGrowth: parseFloat(ordersGrowth),
    revenueGrowth: parseFloat(revenueGrowth),
    visitorsGrowth: parseFloat(visitorsGrowth),
    conversionGrowth: parseFloat(conversionGrowth),
    today: data[data.length - 1]
  }
}

